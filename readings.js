// Readable Cyrillic transliteration (not a phonetic transcription).
window.romanizeRussian = text => {
  const from='абвгдежзийклмнопрстуфхцчшщъыьэюя';
  const to=['a','b','v','g','d','e','zh','z','i','y','k','l','m','n','o','p','r','s','t','u','f','kh','ts','ch','sh','shch','ʺ','y','ʹ','e','yu','ya'];
  const map=Object.fromEntries([...from].map((char,index)=>[char,to[index]]));
  return [...text].map(char=>{
    const roman=char.toLowerCase()==='ё'?'yo':map[char.toLowerCase()];
    return roman===undefined?char:(char===char.toUpperCase()?roman[0].toUpperCase()+roman.slice(1):roman);
  }).join('');
};
